"""Writes schema.sql (PostgreSQL) from the models."""
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from app import app
from audit import GUARD_SQL
from extensions import db

with app.app_context():
    dialect = postgresql.dialect()
    parts = ["-- VaultProof  schema (PostgreSQL), generated by export_schema.py"]
    for table in db.metadata.sorted_tables:
        parts.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";")
        for index in table.indexes:
            parts.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
    parts.append("-- Audit log protection")
    parts += [s.strip() + ";" for s in GUARD_SQL]
    open("schema.sql", "w", encoding="utf-8").write("\n\n".join(parts) + "\n")
    print("schema.sql written")